#!/usr/bin/env node
// Encrypts private/work.json into locked.js so company projects only show
// after a visitor types the password.
//
//   node tools/lock.mjs "new-password"
//
// AES-256-GCM with a PBKDF2-SHA256 key. The page decrypts in the browser, so the
// plain text never ships. Do NOT deploy the private/ folder.

import { readFile, writeFile } from "node:fs/promises";
import { webcrypto as crypto } from "node:crypto";

const password = process.argv[2] || process.env.AKIKO_PASSWORD;
if (!password) {
  console.error('Usage: node tools/lock.mjs "your-password"');
  process.exit(1);
}

const root = new URL("..", import.meta.url);
const plain = await readFile(new URL("private/work.json", root));
JSON.parse(plain); // fail early on broken JSON

const ITER = 250_000;
const salt = crypto.getRandomValues(new Uint8Array(16));
const iv = crypto.getRandomValues(new Uint8Array(12));
const base = await crypto.subtle.importKey("raw", new TextEncoder().encode(password), "PBKDF2", false, ["deriveKey"]);
const key = await crypto.subtle.deriveKey(
  { name: "PBKDF2", salt, iterations: ITER, hash: "SHA-256" },
  base,
  { name: "AES-GCM", length: 256 },
  false,
  ["encrypt"]
);
const data = new Uint8Array(await crypto.subtle.encrypt({ name: "AES-GCM", iv }, key, plain));
const b64 = (u) => Buffer.from(u).toString("base64");

await writeFile(
  new URL("locked.js", root),
  "// Generated by tools/lock.mjs: encrypted company projects. Do not edit by hand.\n" +
    `window.LOCKED = ${JSON.stringify({ iter: ITER, salt: b64(salt), iv: b64(iv), data: b64(data) })};\n`
);
console.log("locked.js written");
